"""Builds lib/site.js (content + render functions) and app/globals.css
from the single-file prototype (index.html).

Usage: python3 scripts/gen_site.py path/to/index.html
"""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '../ruta-suiza/index.html').read_text()
root = pathlib.Path(__file__).resolve().parent.parent

# ---- CSS
css = re.search(r'<style>(.*?)</style>', src, re.S).group(1)
(root / 'app' / 'globals.css').write_text(css.strip() + '\n')

# ---- JS: everything between the i18n header and the router
js = re.search(r'<script>(.*)</script>', src, re.S).group(1)
a = js.index('/* ---------- i18n ---------- */')
b = js.index('/* ---------- router ---------- */')
body = js[a:b]

def rep(old, new, count=1):
    global body
    n = body.count(old)
    if n != count:
        raise SystemExit(f'expected {count} x {old[:60]!r}, found {n}')
    body = body.replace(old, new)

rep("let LANG='es';\ntry{const s=localStorage.getItem('rs-lang');if(s==='fr'||s==='es')LANG=s;}catch(e){}",
    "let LANG='es';\nexport function setLang(l){LANG=l==='fr'?'fr':'es';}\nexport function getLang(){return LANG;}\n"
    "let bindUnlock=()=>{};\nexport function setBindUnlock(f){bindUnlock=f;}")

# renderResult: return the HTML so it can be rendered on the server too
rep("function renderResult(){\n  const r=route(), el=document.getElementById('res'); if(!el) return;\n  el.innerHTML=`",
    "function resultHTML(){\n  const r=route();\n  return `")
rep("  ${offerBlock(r)}`;\n  bindUnlock();\n}",
    "  ${offerBlock(r)}`;\n}\n"
    "function renderResult(){const el=typeof document!=='undefined'&&document.getElementById('res');if(!el)return;el.innerHTML=resultHTML();bindUnlock();}")
rep('<section class="result" id="res" aria-live="polite"></section>',
    '<section class="result" id="res" aria-live="polite">${resultHTML()}</section>')

# checker rows: render on the server too
rep("function renderChk(){\n  const el=document.getElementById('h-res'); if(!el) return;\n  el.innerHTML=chkResult()",
    "function chkRows(){return chkResult()")
body = body.replace(
    "<span class=\"go\">→</span></a>`).join('');\n}",
    "<span class=\"go\">→</span></a>`).join('');}\n"
    "function renderChk(){const el=typeof document!=='undefined'&&document.getElementById('h-res');if(!el)return;el.innerHTML=chkRows();}", 1)
rep('<div class="docs" id="h-res" style="margin-top:14px"></div>',
    '<div class="docs" id="h-res" style="margin-top:14px">${chkRows()}</div>')

exports = ['T', 'UI', 'C', 'ORDER', 'G', 'GORDER', 'TABS', 'LEGAL', 'NEWS', 'NCAT', 'CANTONS', 'MOTIVES',
           'S', 'CHK', 'vInicio', 'vRuta', 'vPaises', 'vPais', 'vGuias', 'vGuia', 'vInstalados', 'vNews',
           'vPrecios', 'vLegal', 'renderResult', 'renderChk', 'bindHub', 'bindNews', 'bindContact',
           'helpBanner', 'route']
header = '/* Generated by scripts/gen_site.py from the prototype. Edit the content there or here, then rebuild. */\n'
out = header + body + '\nexport {' + ','.join(exports) + '};\n'
(root / 'lib' / 'site.js').write_text(out)
print('ok', len(out))
